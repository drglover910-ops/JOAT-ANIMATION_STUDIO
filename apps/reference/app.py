def fetch_all_ghl_files() -> list:
    """
    Read every active media-file record for this GHL location.

    IMPORTANT:
    GHL's parentId query parameter was empirically confirmed not to provide
    reliable folder filtering for type=file. JOAT therefore performs ONE
    read-only fetch and filters by each record's parentId client-side.
    """

    if not GHL_API_KEY:
        raise RuntimeError(
            "GHL_API_KEY is not configured."
        )

    response = requests.get(
        f"{GHL_BASE}/medias/files",
        headers=GHL_HEADERS,
        params={
            "altId": LOCATION_ID,
            "altType": "location",
            "type": "file",
            "sortBy": "createdAt",
            "fetchAll": "true",
        },
        timeout=30,
    )

    response.raise_for_status()

    payload = response.json()

    if not isinstance(
        payload,
        dict,
    ):
        raise RuntimeError(
            "GHL returned an invalid media-list response."
        )

    files = payload.get(
        "files",
        [],
    )

    if not isinstance(
        files,
        list,
    ):
        raise RuntimeError(
            "GHL media-list response did not contain a valid files list."
        )

    return files


def active_ghl_file(
    record: dict,
) -> bool:
    """
    Determine whether a returned GHL record represents a usable completed
    media item.

    We intentionally DO NOT require record['type'] == 'file' here because
    the request itself already asks GHL for type=file. This prevents a valid
    image from disappearing merely because GHL omits or changes the returned
    representation of the type field.
    """
    if not isinstance(
        record,
        dict,
    ):
        return False

    return (
        not record.get(
            "deleted",
            False,
        )
        and not record.get(
            "pendingUpload",
            False,
        )
    )


