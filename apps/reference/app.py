@spaces.GPU(duration=180)
def character_edit(
    image,
    prompt,
    seed=42,
    randomize_seed=False,
    guidance_scale=1.0,
    steps=50,
):
    if image is None:
        raise gr.Error(
            "Upload or select a character reference first."
        )

    if not prompt or not prompt.strip():
        raise gr.Error(
            "Enter an edit instruction."
        )

    image = image.convert(
        "RGB"
    )

    if randomize_seed:
        seed = random.randint(
            0,
            MAX_SEED,
        )

    generator = torch.Generator(
        device=device
    ).manual_seed(
        int(seed)
    )

    print(
        "[JOAT] Generating | "
        f"seed={int(seed)} | "
        f"steps={int(steps)}"
    )

    result = pipe(
        image=[image],
        prompt=prompt.strip(),
        negative_prompt=" ",
        guidance_scale=float(
            guidance_scale
        ),
        num_inference_steps=int(
            steps
        ),
        generator=generator,
        num_images_per_prompt=1,
    )

    output = result.images[0]

    return output, int(seed)


