def load_character_registry() -> dict:
    if not os.path.exists(CHARACTER_FILE):
        raise RuntimeError(
            f"{CHARACTER_FILE} is missing. "
            "JOAT character registry cannot start."
        )

    with open(
        CHARACTER_FILE,
        "r",
        encoding="utf-8",
    ) as f:
        data = json.load(f)

    if not isinstance(data, dict):
        raise RuntimeError(
            f"{CHARACTER_FILE} must contain a JSON object."
        )

    for char_id, character in data.items():
        if not isinstance(character, dict):
            raise RuntimeError(
                f"{char_id} must contain a JSON object."
            )

        character.setdefault("name", char_id)
        character.setdefault("status", "wip")
        character.setdefault("primary", "")
        character.setdefault("face", None)
        character.setdefault("references", [])
        character.setdefault("voice", "")

        # GHL routing
        character.setdefault("ghl_folder_id", "")
        character.setdefault("ghl_identity_folder_id", "")
        character.setdefault("ghl_appearance_folder_id", "")
        character.setdefault("ghl_story_folder_id", "")
        character.setdefault("ghl_mature_folder_id", "")
        character.setdefault("ghl_performance_folder_id", "")

        # New normalized category-folder map.
        character.setdefault("ghl_category_folders", {})

        if not isinstance(
            character["ghl_category_folders"],
            dict,
        ):
            raise RuntimeError(
                f"{char_id}.ghl_category_folders must be a JSON object."
            )

        # Preserve compatibility with the existing flat folder-ID schema.
        flat_folder_map = {
            "identity": character.get(
                "ghl_identity_folder_id",
                "",
            ),
            "appearance": character.get(
                "ghl_appearance_folder_id",
                "",
            ),
            "story": character.get(
                "ghl_story_folder_id",
                "",
            ),
            "mature": character.get(
                "ghl_mature_folder_id",
                "",
            ),
            "performance": character.get(
                "ghl_performance_folder_id",
                "",
            ),
        }

        for asset_type, folder_id in flat_folder_map.items():
            if (
                folder_id
                and not character["ghl_category_folders"].get(
                    asset_type
                )
            ):
                character["ghl_category_folders"][
                    asset_type
                ] = folder_id

        # Audited live GHL fallback.
        known_folders = KNOWN_GHL_CATEGORY_FOLDERS.get(
            char_id,
            {},
        )

        for asset_type, folder_id in known_folders.items():
            if not character["ghl_category_folders"].get(
                asset_type
            ):
                character["ghl_category_folders"][
                    asset_type
                ] = folder_id

        # Keep flat fields synchronized for backward compatibility.
        for asset_type in (
            "identity",
            "appearance",
            "story",
            "mature",
            "performance",
        ):
            folder_id = character[
                "ghl_category_folders"
            ].get(
                asset_type,
                "",
            )

            if folder_id:
                character[
                    f"ghl_{asset_type}_folder_id"
                ] = folder_id

        # Canonical character asset registry
        character.setdefault("assets", {})

        assets = character["assets"]

        if not isinstance(assets, dict):
            raise RuntimeError(
                f"{char_id}.assets must be a JSON object."
            )

        default_assets = {
            "identity": character.get("primary", ""),
            "face": character.get("face") or "",
            "appearance": "",
            "story": "",
            "mature": "",
            "performance": "",
        }

        for asset_type, fallback_url in default_assets.items():
            asset = assets.setdefault(
                asset_type,
                {},
            )

            if not isinstance(asset, dict):
                raise RuntimeError(
                    f"{char_id}.assets.{asset_type} "
                    "must be a JSON object."
                )

            asset.setdefault(
                "url",
                fallback_url,
            )

            asset.setdefault(
                "status",
                (
                    "complete"
                    if asset.get("url")
                    else "missing"
                ),
            )

            asset.setdefault(
                "media_id",
                "",
            )

        if not isinstance(
            character["references"],
            list,
        ):
            raise RuntimeError(
                f"{char_id}.references must be a list."
            )

    return data


