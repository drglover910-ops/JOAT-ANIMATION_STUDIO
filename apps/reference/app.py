    # Additive candidate path; the qualified single-image path remains intact.
    generator = torch.Generator(device=device).manual_seed(42)
    result = pipe(image=images, prompt=prompt, negative_prompt=" ",
                  width=width, height=height,
                  guidance_scale=1.0, num_inference_steps=50,
                  generator=generator, num_images_per_prompt=1)
    return result.images[0]


