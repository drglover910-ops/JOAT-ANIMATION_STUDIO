def save_character_registry_atomic() -> None:
    """
    Safely persist the in-memory character registry.
    """
    target_path = os.path.abspath(
        CHARACTER_FILE
    )

    directory = os.path.dirname(
        target_path
    )

    fd, temp_path = tempfile.mkstemp(
        prefix=".characters-",
        suffix=".json.tmp",
        dir=directory,
    )

    try:
        with os.fdopen(
            fd,
            "w",
            encoding="utf-8",
        ) as f:
            json.dump(
                CHARACTERS,
                f,
                indent=2,
                ensure_ascii=False,
            )

            f.write("\n")

            f.flush()
            os.fsync(
                f.fileno()
            )

        os.replace(
            temp_path,
            target_path,
        )

    finally:
        if os.path.exists(
            temp_path
        ):
            try:
                os.remove(
                    temp_path
                )
            except OSError:
                pass


def register_character_asset(
    char_id: str,
    asset_type: str,
    url: str,
    media_id: str = "",
) -> dict:
    """
    Register a successfully uploaded GHL asset as canonical.
    """

    if asset_type not in ASSET_TYPES:
        raise ValueError(
            f"Unknown asset type: {asset_type}"
        )

    if not url or not url.strip():
        raise ValueError(
            "Cannot register an asset without a GHL URL."
        )

    url = url.strip()

    media_id = (
        media_id.strip()
        if isinstance(media_id, str)
        else ""
    )

    with CHARACTER_REGISTRY_LOCK:
        character = get_character(
            char_id
        )

        assets = character.setdefault(
            "assets",
            {},
        )

        asset = assets.setdefault(
            asset_type,
            {},
        )

        asset["status"] = "complete"
        asset["url"] = url
        asset["media_id"] = media_id

        if asset_type == "identity":
            character["primary"] = url

        elif asset_type == "face":
            character["face"] = url

        save_character_registry_atomic()

        return dict(
            asset
        )


