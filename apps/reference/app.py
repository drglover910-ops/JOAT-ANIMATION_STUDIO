def resolve_ghl_folder(
    char_id: str,
    asset_type: str = "",
) -> str:
    character = get_character(
        char_id
    )

    # Current GHL architecture stores Face with Identity.
    if asset_type == "face":
        asset_type = "identity"

    if asset_type:
        folders = get_category_folder_map(
            char_id
        )

        folder_id = folders.get(
            asset_type,
            "",
        )

        if folder_id:
            return folder_id

    return character.get(
        "ghl_folder_id",
        "",
    )


