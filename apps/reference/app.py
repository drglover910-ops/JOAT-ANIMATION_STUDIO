def get_character(
    char_id: str,
) -> dict:
    character = CHARACTERS.get(
        char_id
    )

    if not character:
        raise ValueError(
            f"Unknown char_id: {char_id}"
        )

    return character


def get_character_asset(
    char_id: str,
    asset_type: str,
) -> dict:
    if asset_type not in ASSET_TYPES:
        raise ValueError(
            f"Unknown asset type: {asset_type}"
        )

    character = get_character(
        char_id
    )

    assets = character.get(
        "assets",
        {},
    )

    return assets.get(
        asset_type,
        {
            "status": "missing",
            "url": "",
            "media_id": "",
        },
    )


def character_has_asset(
    char_id: str,
    asset_type: str,
) -> bool:
    asset = get_character_asset(
        char_id,
        asset_type,
    )

    return (
        asset.get("status") == "complete"
        and bool(asset.get("url"))
    )


def character_missing_assets(
    char_id: str,
) -> list[str]:
    missing = []

    for asset_type in ASSET_TYPES:
        if not character_has_asset(
            char_id,
            asset_type,
        ):
            missing.append(
                asset_type
            )

    return missing


def character_missing_generatable_assets(
    char_id: str,
) -> list[str]:
    """
    Return only missing assets that JOAT is allowed to generate.
    Identity and face are deliberately excluded.
    """
    missing = []

    for asset_type in GENERATABLE_ASSET_TYPES:
        if not character_has_asset(
            char_id,
            asset_type,
        ):
            missing.append(
                asset_type
            )

    return missing


def get_next_missing_asset(
    char_id: str,
):
    """
    Return the next missing generatable canonical asset.

    Generation order:
      appearance -> story -> mature -> performance

    Identity and face are never returned.
    """
    missing = character_missing_generatable_assets(
        char_id
    )

    if not missing:
        return None

    return missing[0]


def character_generation_complete(
    char_id: str,
) -> bool:
    return (
        len(
            character_missing_generatable_assets(
                char_id
            )
        )
        == 0
    )


def character_is_complete(
    char_id: str,
) -> bool:
    return (
        len(
            character_missing_assets(
                char_id
            )
        )
        == 0
    )


