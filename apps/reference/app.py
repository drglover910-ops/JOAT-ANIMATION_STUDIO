def scan_ghl_character_assets(
    char_id: str,
    all_files=None,
) -> dict:
    """
    Read-only live GHL scan.

    Returns:
        {
            "identity": [...],
            "face": [...],
            "appearance": [...],
            "story": [...],
            "mature": [...],
            "performance": [...]
        }

    Face lives inside Identity, so face presence is resolved separately
    during reconciliation using the registered face URL/media ID.
    """

    get_character(
        char_id
    )

    folders = get_category_folder_map(
        char_id
    )

    required_folder_types = (
        "identity",
        "appearance",
        "story",
        "mature",
        "performance",
    )

    missing_folder_config = [
        asset_type
        for asset_type in required_folder_types
        if not folders.get(
            asset_type
        )
    ]

    if missing_folder_config:
        raise RuntimeError(
            f"{char_id} is missing GHL folder configuration for: "
            + ", ".join(
                missing_folder_config
            )
        )

    if all_files is None:
        all_files = fetch_all_ghl_files()

    folder_to_category = {
        folder_id: asset_type
        for asset_type, folder_id in folders.items()
        if folder_id
    }

    inventory = {
        "identity": [],
        "face": [],
        "appearance": [],
        "story": [],
        "mature": [],
        "performance": [],
    }

    for record in all_files:
        if not active_ghl_file(
            record
        ):
            continue

        parent_id = (
            record.get(
                "parentId",
                "",
            )
            or ""
        )

        asset_type = folder_to_category.get(
            parent_id
        )

        if not asset_type:
            continue

        inventory[
            asset_type
        ].append(
            normalize_ghl_file(
                record
            )
        )

    return inventory


def record_matches_asset(
    record: dict,
    asset: dict,
) -> bool:
    """
    Match a registry asset against a live GHL record using stable media ID
    first and URL second.
    """

    media_id = (
        asset.get(
            "media_id",
            "",
        )
        or ""
    )

    url = (
        asset.get(
            "url",
            "",
        )
        or ""
    )

    record_media_id = (
        record.get(
            "media_id",
            "",
        )
        or ""
    )

    record_url = (
        record.get(
            "url",
            "",
        )
        or ""
    )

    if (
        media_id
        and record_media_id
        and media_id == record_media_id
    ):
        return True

    if (
        url
        and record_url
        and url == record_url
    ):
        return True

    return False


def choose_canonical_file(
    files: list,
) -> dict | None:
    """
    Pick a deterministic canonical representative from an existing GHL
    category when the registry has not yet recorded one.

    Prefer the oldest existing file so original character assets win over
    later generated outputs.
    """

    usable = [
        record
        for record in files
        if record.get(
            "url"
        )
    ]

    if not usable:
        return None

    usable.sort(
        key=lambda record: (
            record.get(
                "createdAt"
            )
            or "",
            record.get(
                "media_id"
            )
            or "",
        )
    )

    return usable[0]


def reconcile_character_with_ghl(
    char_id: str,
    all_files=None,
    persist=True,
) -> dict:
    """
    Reconcile characters.json with the actual live GHL media inventory.

    GHL folder presence is authoritative for generatable category presence.

    Identity:
      Present when the Identity folder contains files.
      Existing registered primary is preserved when it still exists.
      Otherwise a deterministic existing Identity file is selected.

    Face:
      Face shares the Identity folder, so JOAT does NOT infer that every
      Identity image is a Face asset. Existing face registration is preserved
      only when that exact media ID/URL exists in Identity.

    Appearance / Story / Mature / Performance:
      If the category folder contains at least one live file, the category is
      complete. Existing canonical registration is preserved when possible;
      otherwise an existing file is adopted into the registry.

    This function performs no generation, upload, move, or delete operation.
    """

    character = get_character(
        char_id
    )

    inventory = scan_ghl_character_assets(
        char_id,
        all_files=all_files,
    )

    changed = False

    with CHARACTER_REGISTRY_LOCK:
        assets = character.setdefault(
            "assets",
            {},
        )

        for asset_type in ASSET_TYPES:
            assets.setdefault(
                asset_type,
                {
                    "status": "missing",
                    "url": "",
                    "media_id": "",
                },
            )

        # ── IDENTITY ────────────────────────────────────────────────────────

        identity_files = inventory.get(
            "identity",
            [],
        )

        identity_asset = assets[
            "identity"
        ]

        identity_match = None

        for record in identity_files:
            if record_matches_asset(
                record,
                identity_asset,
            ):
                identity_match = record
                break

        if identity_match is None:
            primary_url = (
                character.get(
                    "primary",
                    "",
                )
                or ""
            )

            for record in identity_files:
                if (
                    primary_url
                    and record.get(
                        "url"
                    ) == primary_url
                ):
                    identity_match = record
                    break

        if identity_match is None:
            identity_match = choose_canonical_file(
                identity_files
            )

        if identity_match:
            desired_identity = {
                "status": "complete",
                "url": identity_match.get(
                    "url",
                    "",
                ),
                "media_id": identity_match.get(
                    "media_id",
                    "",
                ),
            }

            for key, value in desired_identity.items():
                if identity_asset.get(
                    key
                ) != value:
                    identity_asset[
                        key
                    ] = value
                    changed = True

            if (
                character.get(
                    "primary",
                    ""
                )
                != desired_identity[
                    "url"
                ]
            ):
                character[
                    "primary"
                ] = desired_identity[
                    "url"
                ]
                changed = True

        else:
            if identity_asset.get(
                "status"
            ) != "missing":
                identity_asset[
                    "status"
                ] = "missing"
                changed = True

        # ── FACE ────────────────────────────────────────────────────────────
        # Face cannot safely be inferred merely from "some file exists in the
        # Identity folder". Preserve it only when the registered face record
        # actually exists in that folder.

        face_asset = assets[
            "face"
        ]

        face_url = (
            character.get(
                "face"
            )
            or face_asset.get(
                "url",
                "",
            )
            or ""
        )

        face_media_id = (
            face_asset.get(
                "media_id",
                "",
            )
            or ""
        )

        face_match = None

        for record in identity_files:
            record_media_id = (
                record.get(
                    "media_id",
                    "",
                )
                or ""
            )

            record_url = (
                record.get(
                    "url",
                    "",
                )
                or ""
            )

            if (
                face_media_id
                and record_media_id
                and face_media_id == record_media_id
            ):
                face_match = record
                break

            if (
                face_url
                and record_url
                and face_url == record_url
            ):
                face_match = record
                break

        if face_match:
            desired_face = {
                "status": "complete",
                "url": face_match.get(
                    "url",
                    "",
                ),
                "media_id": face_match.get(
                    "media_id",
                    "",
                ),
            }

            for key, value in desired_face.items():
                if face_asset.get(
                    key
                ) != value:
                    face_asset[
                        key
                    ] = value
                    changed = True

            if (
                character.get(
                    "face"
                )
                != desired_face[
                    "url"
                ]
            ):
                character[
                    "face"
                ] = desired_face[
                    "url"
                ]
                changed = True

            inventory[
                "face"
            ] = [
                face_match
            ]

        else:
            if face_asset.get(
                "status"
            ) != "missing":
                face_asset[
                    "status"
                ] = "missing"
                changed = True

            inventory[
                "face"
            ] = []

        # ── GENERATABLE CATEGORIES ──────────────────────────────────────────

        for asset_type in GENERATABLE_ASSET_TYPES:
            files = inventory.get(
                asset_type,
                [],
            )

            asset = assets[
                asset_type
            ]

            canonical = None

            for record in files:
                if record_matches_asset(
                    record,
                    asset,
                ):
                    canonical = record
                    break

            if canonical is None:
                canonical = choose_canonical_file(
                    files
                )

            if canonical:
                desired = {
                    "status": "complete",
                    "url": canonical.get(
                        "url",
                        "",
                    ),
                    "media_id": canonical.get(
                        "media_id",
                        "",
                    ),
                }

                for key, value in desired.items():
                    if asset.get(
                        key
                    ) != value:
                        asset[
                            key
                        ] = value
                        changed = True

            else:
                if asset.get(
                    "status"
                ) != "missing":
                    asset[
                        "status"
                    ] = "missing"
                    changed = True

                if asset.get(
                    "url",
                    ""
                ):
                    asset[
                        "url"
                    ] = ""
                    changed = True

                if asset.get(
                    "media_id",
                    ""
                ):
                    asset[
                        "media_id"
                    ] = ""
                    changed = True

        if changed and persist:
            save_character_registry_atomic()

    result = {
        "char_id": char_id,
        "inventory": inventory,
        "counts": {
            asset_type: len(
                inventory.get(
                    asset_type,
                    [],
                )
            )
            for asset_type in ASSET_TYPES
        },
        "missing_assets": character_missing_assets(
            char_id
        ),
        "missing_generatable_assets":
            character_missing_generatable_assets(
                char_id
            ),
        "next_missing_asset":
            get_next_missing_asset(
                char_id
            ),
        "generation_complete":
            character_generation_complete(
                char_id
            ),
        "character_complete":
            character_is_complete(
                char_id
            ),
        "registry_changed": changed,
        "live_scan": True,
    }

    print(
        "[JOAT GHL RECONCILE] "
        f"{char_id} | "
        f"counts={result['counts']} | "
        f"next={result['next_missing_asset']} | "
        f"changed={changed}"
    )

    return result


