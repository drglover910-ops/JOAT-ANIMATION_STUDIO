def load_from_url(
    url: str,
) -> Image.Image:
    if not url:
        raise ValueError(
            "Image URL is required."
        )

    r = requests.get(
        url,
        timeout=30,
    )

    r.raise_for_status()

    return Image.open(
        io.BytesIO(
            r.content
        )
    ).convert(
        "RGB"
    )


def force_16x9(
    img: Image.Image,
) -> Image.Image:
    """
    Fit the complete source image inside a 640x360 canvas
    without cropping the subject.
    """
    img = img.convert(
        "RGB"
    )

    img.thumbnail(
        (
            TARGET_W,
            TARGET_H,
        ),
        Image.Resampling.LANCZOS,
    )

    canvas = Image.new(
        "RGB",
        (
            TARGET_W,
            TARGET_H,
        ),
        (
            0,
            0,
            0,
        ),
    )

    x = (
        TARGET_W - img.width
    ) // 2

    y = (
        TARGET_H - img.height
    ) // 2

    canvas.paste(
        img,
        (
            x,
            y,
        ),
    )

    return canvas


def to_b64(
    img: Image.Image,
) -> str:
    buf = io.BytesIO()

    img.save(
        buf,
        format="PNG",
    )

    return base64.b64encode(
        buf.getvalue()
    ).decode(
        "utf-8"
    )


def from_b64(
    data: str,
) -> Image.Image:
    if not data:
        raise ValueError(
            "image_b64 is required."
        )

    raw = base64.b64decode(
        data
    )

    return Image.open(
        io.BytesIO(
            raw
        )
    ).convert(
        "RGB"
    )


def prepare_ref(
    url: str,
) -> Image.Image:
    return force_16x9(
        load_from_url(
            url
        )
    )


def upload_to_ghl(
    img: Image.Image,
    filename: str,
    folder_id: str = "",
) -> dict:
    if not GHL_API_KEY:
        raise RuntimeError(
            "GHL_API_KEY is not configured."
        )

    buf = io.BytesIO()

    img.save(
        buf,
        format="PNG",
    )

    buf.seek(0)

    files = {
        "file": (
            filename,
            buf,
            "image/png",
        )
    }

    data = {
        "altId": LOCATION_ID,
        "altType": "location",
        "name": filename,
    }

    if folder_id:
        data[
            "parentId"
        ] = folder_id

    r = requests.post(
        f"{GHL_BASE}/medias/upload-file",
        headers=GHL_HEADERS,
        files=files,
        data=data,
        timeout=60,
    )

    r.raise_for_status()

    result = r.json()

    if not isinstance(
        result,
        dict,
    ):
        raise RuntimeError(
            "GHL returned an invalid upload response."
        )

    return result


